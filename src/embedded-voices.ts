export type EmbeddedVoiceName = keyof typeof EMBEDDED_VOICE_MANIFEST;
type VoiceProvider = (voice: string) => Promise<ArrayBuffer>;

const VOICE_PROVIDER = Symbol.for("kokoro-js.voice-provider");

export async function loadEmbeddedVoice(voice: string): Promise<ArrayBuffer> {
  if (!Object.hasOwn(EMBEDDED_VOICE_MANIFEST, voice)) {
    throw new Error(`Embedded Kokoro voice not found: ${voice}`);
  }

  const entry = EMBEDDED_VOICE_MANIFEST[voice as EmbeddedVoiceName];
  return Bun.file(entry.assetPath).arrayBuffer();
}

export function installEmbeddedVoiceProvider(): () => void {
  const globals = globalThis as typeof globalThis & Record<symbol, unknown>;
  const previous = globals[VOICE_PROVIDER];
  globals[VOICE_PROVIDER] = loadEmbeddedVoice satisfies VoiceProvider;

  return () => {
    if (previous === undefined) {
      delete globals[VOICE_PROVIDER];
    } else {
      globals[VOICE_PROVIDER] = previous;
    }
  };
}

export async function verifyEmbeddedVoices(): Promise<EmbeddedVoiceName[]> {
  const voices = Object.keys(EMBEDDED_VOICE_MANIFEST) as EmbeddedVoiceName[];
  if (voices.length !== EXPECTED_VOICE_COUNT || !voices.includes("af_heart")) {
    throw new Error(
      `Embedded voice manifest must contain ${EXPECTED_VOICE_COUNT} voices including af_heart`,
    );
  }

  for (const voice of voices) {
    const bytes = await loadEmbeddedVoice(voice);
    const actual = Bun.CryptoHasher.hash("sha256", bytes, "hex");
    const expected = EMBEDDED_VOICE_MANIFEST[voice].sha256;
    if (actual !== expected) {
      throw new Error(`Embedded voice hash mismatch for ${voice}`);
    }
  }

  return voices;
}
